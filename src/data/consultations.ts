/** Цена в евро от „35 €"; 0 за безплатните. */
export function bookingPriceEur(pkg: Package): number {
  const n = parseFloat(pkg.price.replace(/[^0-9.]/g, ""));
  return Number.isFinite(n) && n > 0 ? n : 0;
}

export function findBookingPackage(id: string): Package | undefined {
  return [...CONSULTATION_PACKAGES, ...TRAINING_PACKAGES].find((p) => p.id === id);
}
